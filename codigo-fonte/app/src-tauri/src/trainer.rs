use serde_json::Value;
use tauri_plugin_opener::OpenerExt;

/// Heavy scans and OCR run outside the app's event thread.
#[tauri::command]
pub async fn trainer_call(app: tauri::AppHandle, request: Value) -> Result<Value, String> {
    let export = request.get("cmd").and_then(Value::as_str) == Some("export_plan");
    let result = tauri::async_runtime::spawn_blocking(move || fmlibre_trainer::handle(request).map_err(|e|format!("{e:#}")))
        .await.map_err(|e|e.to_string())??;
    if export {
        if let Some(path) = result.get("html").and_then(Value::as_str) {
            // Only the report just generated by the engine is opened.
            app.opener().open_path(path, None::<&str>).map_err(|e|e.to_string())?;
        }
    }
    Ok(result)
}
